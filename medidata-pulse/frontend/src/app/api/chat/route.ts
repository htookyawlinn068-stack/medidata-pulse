import { NextResponse } from 'next/server';

export async function POST(req: Request) {
  try {
    const { messages } = await req.json();
    const lastMessage = messages[messages.length - 1]?.text || '';

    let replyText = "ကျေးဇူးပြု၍ အသေးစိတ် အခြေအနေကို ထပ်ပြောပြပါ။ အရေးပေါ်အခြေအနေဆိုပါက သက်ဆိုင်ရာဆေးရုံသို့ ချက်ချင်းသွားပါ။";

    const text = lastMessage.toLowerCase();
    
    if (text.includes('ဓား') || text.includes('ရှ') || text.includes('သွေး')) {
      replyText = "ဓားရှ သွေးထွက်ပါက သန့်ရှင်းသော အဝတ် သို့မဟုတ် ပတ်တီးဖြင့် တင်းတင်းဖိထားပါ။ ဒဏ်ရာရထားသောနေရာကို နှလုံးအထက်သို့ မြှင့်ထားပေးပြီး ရေဆေးချပါ။ သွေးမတိတ်ပါက နီးစပ်ရာ ဆေးခန်းသို့ အမြန်ဆုံးသွားပါ။";
    } 
    else if (text.includes('မီးလောင်') || text.includes('ပူ')) {
      replyText = "မီးလောင်ထားသော နေရာကို အေးမြသော ရေစီးကြောင်းအောက်တွင် အနည်းဆုံး (၁၀-၁၅) မိနစ်ခန့် ဆေးကြောပါ။ ရေခဲတိုက်ရိုက်မကပ်ပါနှင့်။ သန့်ရှင်းသော အဝတ်စဖြင့် အုပ်ထားပါ။";
    } 
    else if (text.includes('ရင်ဘတ်') || text.includes('အသက်ရှူ') || text.includes('ရင်ကျပ်')) {
      replyText = "ရင်ဘတ်အောင့်ခြင်း သို့မဟုတ် အသက်ရှူကြပ်ခြင်းဖြစ်ပါက လူနာကို သက်တောင့်သက်သာ ထჯိုင်ခိုင်းပါ သို့မဟုတ် ကျောမှီပေးပါ။ တင်းကျပ်နေသော အဝတ်အစားများကို ဖြေလျော့ပေးပြီး အရေးပေါ် လူနာတင်ယာဉ် (သို့) ဆရာဝန်ထံ ချက်ချင်း အကြောင်းကြားပါ။";
    }
    else if (text.includes('သတိလစ်') || text.includes('မူးလဲ')) {
      replyText = "လူနာ သတိလစ်သွားပါက ဘေးတစောင်းအနေအထား (Recovery Position) သို့ လှဲပေးပါ။ လေလမ်းကြောင်း ပိတ်ဆို့မှု ရှိမရှိ စစ်ဆေးပြီး ပါးစပ်အတွင်း အစားအစာ သို့မဟုတ် အရည် လုံးဝမတိုက်ပါနှင့်။ ချက်ချင်း ဆေးရုံတင်ရန် စီစဉ်ပါ။";
    } 
    else if (text.includes('မြွေ') || text.includes('ကိုက်')) {
      replyText = "မြွေကိုက်ခံရပါက လူနာကို ငြိမ်ငြိမ်ထားပါ။ ကိုက်ခံရသည့်နေရာကို တင်းကျပ်စွာ စည်းနှောင်ခြင်း၊ ဓားဖြင့်စပ်ခြင်း သို့မဟုတ် အဆိပ်စုပ်ထုတ်ခြင်း လုံးဝမလုပ်ပါနှင့်။ နီးစပ်ရာဆေးရုံသို့ အမြန်ဆုံး ပို့ဆောင်ပါ။";
    }
    else if (text.includes('အရိုး') || text.includes('ကျိုး') || text.includes('စစ်')) {
      replyText = "အရိုးကျိုးသည်ဟု ယူဆရပါက ထိခိုက်ထားသော အဆစ် သို့မဟုတ် အရိုးကို လုံးဝ မလှုပ်ရှားခိုင်းပါနှင့်။ တောင့်တင်းသော ပစ္စည်း (Splint) ဖြင့် ထိန်းသိမ်းထားပြီး ဆေးရုံသို့ ပို့ဆောင်ပါ။";
    }
    else if (text.includes('ဓာတ်မတည့်') || text.includes('အလာဂျီ') || text.includes('ယားယံ')) {
      replyText = "ပြင်းထန်စွာ ဓာတ်မတည့်ခြင်း (Allergic Reaction) ဖြစ်ပါက ဓာတ်မတည့်စေသော အရာကို ချက်ချင်း ဖယ်ရှားပါ။ အသက်ရှူကျပ်ခြင်း၊ မျက်နှာနှင့် လည်ချောင်းယောင်ရမ်းခြင်းများရှိပါက အရေးပေါ်ဆေးရုံသို့ ချက်ချင်း ပို့ဆောင်ပါ။";
    }
    else if (text.includes('အဆိပ်') || text.includes('ဆေးမှား') || text.includes('သောက်မိ')) {
      replyText = "အဆိပ်အတောက် သို့မဟုတ် ဆေးဝါးမှားယွင်း သောက်မိပါက လူနာကို အသင့်အတိုင်း ထားရှိပါ။ အတင်းအကြပ် အန်ခိုင်းခြင်း လုံးဝမလုပ်ပါနှင့်။ ဘာပစ္စည်းကို သောက်မိသည်ဆိုသည်ကို တတ်နိုင်သမျှ အမြန်ဆုံး စုံစမ်းပြီး ဆေးရုံသို့ ယူဆောင်သွားပါ။";
    }
    else if (text.includes('လေဖြတ်') || text.includes('မျက်နှာ') || text.includes('စကားပြောမရ')) {
      replyText = "လေဖြတ်ခြင်း (Stroke) လက္ခဏာများဖြစ်သော မျက်နှာစွေခြင်း၊ လက်တစ်ဖက်တည်း အားမရှိခြင်း၊ စကားဝေဝေဝါးဝါး ဖြစ်ခြင်းများ တွေ့ရပါက အချိန်အဆိုင်းမရှိ အရေးပေါ် လူနာတင်ယာဉ်ကို ချက်ချင်း ခေါ်ဆိုပါ။";
    }
    else if (text.includes('နှလုံး') || text.includes('ရင်ဘတ်အောင့်') || text.includes('မူးဝေ')) {
      replyText = "နှလုံးရောဂါလက္ခဏာ သံသයရှိပါက လူနာကို လုံးဝ မလှုပ်ရှားခိုင်းဘဲ အနားပေးပါ။ တင်းကျပ်သော အဝတ်အစားများကို ဖြေလျော့ပေးပြီး လိုအပ်ပါက CPR (နှလုံးနှင့် အဆုတ်ကို အသက်သွင်းခြင်း) ပြုလုပ်ရန် ပြင်ဆင်ပါ။";
    }
    else if (text.includes('ခေါင်း') || text.includes('ထိခိုက်') || text.includes('ဦးနှောက်')) {
      replyText = "ခေါင်းပြင်းထန်စွာ ထိခိုက်မိပါက လူနာကို ငြိမ်ဝပ်စွာ ထားရှိပါ။ အိပ်မပျော်စေရန် ဂရုစိုက်ပါ။ အန်ခြင်း၊ သတိလစ်ခြင်း၊ အမြင်အာရုံ ဝေဝါးခြင်းတို့ ရှိပါက ချက်ချင်း ဆေးရုံသို့ ပို့ဆောင်ပါ။";
    }

    await new Promise(resolve => setTimeout(resolve, 800));

    return NextResponse.json({ reply: replyText });
  } catch (error: any) {
    console.error('API Error:', error);
    return NextResponse.json({ reply: 'စနစ် ချိတ်ဆက်မှု အဆင်မပြေပါ။' }, { status: 500 });
  }
}